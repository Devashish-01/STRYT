// P06: point a local app at STAGING and give each synthetic persona a test phone number.
//
// - Writes .env.staging (gitignored via `.env*`): staging URL, staging publishable key (public by
//   design — it ships inside every client), the staging ref, and a generated test OTP shared by the
//   synthetic persona numbers. Values are never printed.
// - Configures STAGING auth (never production): phone sign-in with those test numbers (no SMS is sent
//   for test numbers), email sign-in auto-confirmed for the admin persona, localhost site URL.
//
// Hard guard: refuses unless the ref is the staging ref in docs/plan/DECISIONS.md (D6) and not production.
// Usage: node scripts/staging/setup-staging-auth.mjs

import fs from "fs";
import path from "path";
import crypto from "crypto";
import { fileURLToPath } from "url";
import { PERSONAS, NEWCOMER_PHONES } from "./personas.mjs";

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), "..", "..");
const PROD = "gnswxlfmcwyhmzlfipql";
const decisions = fs.readFileSync(path.join(ROOT, "docs", "plan", "DECISIONS.md"), "utf8");
const STAGING = decisions.match(/\*\*D6\*\*[^\n]*ref:\s*([a-z0-9]{20})/)?.[1];
if (!STAGING || STAGING === PROD) { console.error("REFUSED: no staging ref in DECISIONS.md D6, or it is production"); process.exit(2); }

const env = {};
for (const line of fs.readFileSync(path.join(ROOT, ".env"), "utf8").split(/\r?\n/)) {
  const m = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*)\s*$/);
  if (m) env[m[1]] = m[2].replace(/^["']|["']$/g, "");
}
const H = { Authorization: `Bearer ${env.SUPABASE_PERSONAL_ACCESS_TOKEN}`, "Content-Type": "application/json" };
const api = async (method, p, body) => {
  const r = await fetch(`https://api.supabase.com/v1/projects/${STAGING}${p}`, { method, headers: H, body: body ? JSON.stringify(body) : undefined });
  const t = await r.text();
  if (!r.ok) throw new Error(`${method} ${p} -> HTTP ${r.status}: ${t.slice(0, 300)}`);
  return t ? JSON.parse(t) : null;
};
console.log("target:", STAGING, "(staging)");

const keys = await api("GET", "/api-keys");
const publishable = keys.find((k) => k.type === "publishable")?.api_key || keys.find((k) => k.name === "anon")?.api_key;
if (!publishable) throw new Error("no publishable/anon key found on staging");

const envFile = path.join(ROOT, ".env.staging");
const existing = fs.existsSync(envFile) ? fs.readFileSync(envFile, "utf8") : "";
const otp = existing.match(/^STAGING_TEST_OTP=(\d{6})$/m)?.[1] || String(crypto.randomInt(100000, 999999));
fs.writeFileSync(envFile, [
  "# STAGING ONLY — generated by scripts/staging/setup-staging-auth.mjs. Never commit (covered by .gitignore `.env*`).",
  "# `vite --mode staging` layers this over .env.",
  `VITE_SUPABASE_URL=https://${STAGING}.supabase.co`,
  `VITE_SUPABASE_ANON_KEY=${publishable}`,
  `STAGING_REF=${STAGING}`,
  `STAGING_TEST_OTP=${otp}`,
  "",
].join("\n"));
console.log(".env.staging written (values not printed); gitignored:", !!fs.readFileSync(path.join(ROOT, ".gitignore"), "utf8").match(/^\.env\*$/m));

const phones = [...PERSONAS.map((p) => p.phone).filter(Boolean), ...NEWCOMER_PHONES]
  .map((phone) => `${phone.replace("+", "")}=${otp}`)
  .join(",");
await api("PATCH", "/config/auth", {
  site_url: "http://localhost:5173",
  uri_allow_list: "http://localhost:5173/**,http://localhost:4173/**,http://127.0.0.1:5173/**",
  external_phone_enabled: true,
  sms_autoconfirm: false,
  sms_test_otp: phones,
  sms_test_otp_valid_until: "2027-12-31T00:00:00Z",
  external_email_enabled: true,
  mailer_autoconfirm: true,
});
const after = await api("GET", "/config/auth");
console.log("staging auth now:", JSON.stringify({
  site_url: after.site_url, external_phone_enabled: after.external_phone_enabled,
  test_otp_numbers: (after.sms_test_otp || "").split(",").filter(Boolean).length, mailer_autoconfirm: after.mailer_autoconfirm,
}));
