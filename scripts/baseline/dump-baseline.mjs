// Rebuildable schema baseline, without Docker, pg_dump or a database password (P06, decision D7a).
//
// Reads production's catalog through the Supabase Management API (read-only SELECTs) and writes two
// restorable, ordered SQL files:
//   supabase/baseline/<date>_schema.sql          app objects in `public` and `private`
//   supabase/baseline/<date>_platform_state.sql  storage buckets + policies, realtime publication, cron jobs
// Every statement is copied from pg_catalog functions (pg_get_functiondef, pg_get_constraintdef,
// pg_get_indexdef, pg_get_triggerdef, pg_get_viewdef, pg_policies, ACLs) — never retyped.
// Items are separated by `-- @@item` lines so scripts/baseline/apply-baseline.mjs can apply them one by one.
//
// Not included (documented in supabase/baseline/README.md): row data, auth/storage/realtime internals owned
// by Supabase, vault secret values, event triggers (need superuser), edge functions and their secrets.
//
// Usage: node scripts/baseline/dump-baseline.mjs [YYYY-MM-DD]

import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), "..", "..");
const PROD = "gnswxlfmcwyhmzlfipql";
const date = process.argv[2] || new Date().toISOString().slice(0, 10);

const env = {};
for (const line of fs.readFileSync(path.join(ROOT, ".env"), "utf8").split(/\r?\n/)) {
  const m = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*)\s*$/);
  if (m) env[m[1]] = m[2].replace(/^["']|["']$/g, "");
}
console.log("source project:", PROD, "(read-only)");

async function q(sql) {
  const r = await fetch(`https://api.supabase.com/v1/projects/${PROD}/database/query`, {
    method: "POST",
    headers: { Authorization: `Bearer ${env.SUPABASE_PERSONAL_ACCESS_TOKEN}`, "Content-Type": "application/json" },
    body: JSON.stringify({ query: sql }),
  });
  const t = await r.text();
  if (!r.ok) throw new Error(`HTTP ${r.status}: ${t.slice(0, 300)}`);
  return JSON.parse(t);
}

const SCHEMAS = "('public'::regnamespace, 'private'::regnamespace)";
const NOT_EXT = (col) => `not exists (select 1 from pg_depend d where d.objid = ${col} and d.deptype = 'e')`;

const SECTIONS = [
  ["Extensions", `
    select format('create extension if not exists %I with schema %I;', e.extname, n.nspname) as ddl
    from pg_extension e join pg_namespace n on n.oid = e.extnamespace
    where e.extname not in ('plpgsql') order by e.extname`],
  ["Schemas", `
    select format('create schema if not exists %I;', nspname) as ddl from pg_namespace where nspname = 'private'`],
  ["Enum types", `
    select format('CREATE TYPE %I.%I AS ENUM (%s);', n.nspname, t.typname,
             string_agg(quote_literal(e.enumlabel), ', ' order by e.enumsortorder)) as ddl
    from pg_type t join pg_namespace n on n.oid = t.typnamespace join pg_enum e on e.enumtypid = t.oid
    where t.typnamespace in ${SCHEMAS} and ${NOT_EXT("t.oid")}
    group by n.nspname, t.typname order by n.nspname, t.typname`],
  ["Tables", `
    select format(E'CREATE TABLE %I.%I (\\n%s\\n);', n.nspname, c.relname,
             string_agg(format('  %I %s%s%s', a.attname, format_type(a.atttypid, a.atttypmod),
               case
                 when a.attidentity = 'a' then ' GENERATED ALWAYS AS IDENTITY'
                 when a.attidentity = 'd' then ' GENERATED BY DEFAULT AS IDENTITY'
                 when d.adbin is not null then ' DEFAULT ' || pg_get_expr(d.adbin, d.adrelid)
                 else '' end,
               case when a.attnotnull then ' NOT NULL' else '' end), E',\\n' order by a.attnum)) as ddl
    from pg_class c join pg_namespace n on n.oid = c.relnamespace
    join pg_attribute a on a.attrelid = c.oid and a.attnum > 0 and not a.attisdropped
    left join pg_attrdef d on d.adrelid = c.oid and d.adnum = a.attnum
    where c.relnamespace in ${SCHEMAS} and c.relkind in ('r', 'p') and ${NOT_EXT("c.oid")}
    group by n.nspname, c.relname order by n.nspname, c.relname`],
  ["Functions", `
    select pg_get_functiondef(p.oid) || ';' as ddl
    from pg_proc p
    where p.pronamespace in ${SCHEMAS} and p.prokind in ('f','p','w') and ${NOT_EXT("p.oid")}
    order by p.pronamespace::regnamespace::text, p.proname, pg_get_function_identity_arguments(p.oid)`],
  ["Views", `
    select format(E'CREATE OR REPLACE VIEW %I.%I %sAS\\n%s', n.nspname, c.relname,
             case when c.reloptions is not null then 'WITH (' || array_to_string(c.reloptions, ', ') || ') ' else '' end,
             pg_get_viewdef(c.oid, true)) as ddl
    from pg_class c join pg_namespace n on n.oid = c.relnamespace
    where c.relnamespace in ${SCHEMAS} and c.relkind = 'v' and ${NOT_EXT("c.oid")} order by c.oid`],
  ["Primary keys, unique, check and exclusion constraints", `
    select format('ALTER TABLE ONLY %s ADD CONSTRAINT %I %s;', k.conrelid::regclass, k.conname, pg_get_constraintdef(k.oid)) as ddl
    from pg_constraint k join pg_class c on c.oid = k.conrelid
    where k.connamespace in ${SCHEMAS} and k.contype in ('p','u','c','x') and ${NOT_EXT("c.oid")}
    order by k.conrelid::regclass::text, case k.contype when 'p' then 0 when 'u' then 1 else 2 end, k.conname`],
  ["Foreign keys", `
    select format('ALTER TABLE ONLY %s ADD CONSTRAINT %I %s;', k.conrelid::regclass, k.conname, pg_get_constraintdef(k.oid)) as ddl
    from pg_constraint k join pg_class c on c.oid = k.conrelid
    where k.connamespace in ${SCHEMAS} and k.contype = 'f' and ${NOT_EXT("c.oid")}
    order by k.conrelid::regclass::text, k.conname`],
  ["Indexes (not backing a constraint)", `
    select pg_get_indexdef(ic.oid) || ';' as ddl
    from pg_index x join pg_class ic on ic.oid = x.indexrelid join pg_class tc on tc.oid = x.indrelid
    where tc.relnamespace in ${SCHEMAS} and not exists (select 1 from pg_constraint k where k.conindid = ic.oid) and ${NOT_EXT("ic.oid")}
    order by tc.relname, ic.relname`],
  ["Triggers", `
    select pg_get_triggerdef(t.oid, true) || ';' as ddl
    from pg_trigger t join pg_class c on c.oid = t.tgrelid join pg_proc p on p.oid = t.tgfoid
    where not t.tgisinternal and (c.relnamespace in ${SCHEMAS} or p.pronamespace in ${SCHEMAS})
    order by c.relnamespace::regnamespace::text, c.relname, t.tgname`],
  ["Row level security", `
    select format('ALTER TABLE %I.%I ENABLE ROW LEVEL SECURITY;', n.nspname, c.relname)
           || case when c.relforcerowsecurity then format(E'\\nALTER TABLE %I.%I FORCE ROW LEVEL SECURITY;', n.nspname, c.relname) else '' end as ddl
    from pg_class c join pg_namespace n on n.oid = c.relnamespace
    where c.relnamespace in ${SCHEMAS} and c.relkind in ('r','p') and c.relrowsecurity order by n.nspname, c.relname`],
  ["Policies", `
    select format(E'CREATE POLICY %I ON %I.%I AS %s FOR %s TO %s%s%s;', policyname, schemaname, tablename, permissive, cmd,
             (select string_agg(case when r = 'public' then 'PUBLIC' else quote_ident(r) end, ', ') from unnest(roles) r),
             case when qual is not null then E'\\n  USING (' || qual || ')' else '' end,
             case when with_check is not null then E'\\n  WITH CHECK (' || with_check || ')' else '' end) as ddl
    from pg_policies where schemaname in ('public', 'private') order by schemaname, tablename, policyname`],
  ["Table and view grants (exact: revoke defaults, then grant)", `
    select format('REVOKE ALL ON TABLE %I.%I FROM anon, authenticated, service_role;', n.nspname, c.relname)
             || coalesce((select string_agg(format(E'\\nGRANT %s ON TABLE %I.%I TO %s;', g.privs, n.nspname, c.relname, g.grantee), '' order by g.grantee)
               from (select grantee, string_agg(privilege_type, ', ' order by privilege_type) privs
                       from information_schema.role_table_grants rtg
                      where rtg.table_schema = n.nspname and rtg.table_name = c.relname and rtg.grantee in ('anon','authenticated','service_role')
                      group by grantee) g), '')
             || coalesce((select string_agg(format(E'\\nGRANT %s (%s) ON TABLE %I.%I TO %s;', cg.priv, cg.cols, n.nspname, c.relname, cg.grantee), '' order by cg.grantee, cg.priv)
               from (select cp.grantee, cp.privilege_type priv, string_agg(quote_ident(cp.column_name), ', ' order by a.attnum) cols
                       from information_schema.column_privileges cp
                       join pg_attribute a on a.attrelid = c.oid and a.attname = cp.column_name
                      where cp.table_schema = n.nspname and cp.table_name = c.relname and cp.grantee in ('anon','authenticated','service_role')
                        and not exists (select 1 from information_schema.role_table_grants rtg where rtg.table_schema = cp.table_schema
                              and rtg.table_name = cp.table_name and rtg.grantee = cp.grantee and rtg.privilege_type = cp.privilege_type)
                      group by cp.grantee, cp.privilege_type) cg), '') as ddl
    from pg_class c join pg_namespace n on n.oid = c.relnamespace
    where c.relnamespace in ${SCHEMAS} and c.relkind in ('r','p','v') and ${NOT_EXT("c.oid")} order by n.nspname, c.relname`],
  ["Function EXECUTE grants (exact: revoke defaults, then grant)", `
    select format(E'REVOKE ALL ON FUNCTION %I.%I(%s) FROM PUBLIC, anon, authenticated, service_role;%s',
             n.nspname, p.proname, pg_get_function_identity_arguments(p.oid),
             coalesce(string_agg(format(E'\\nGRANT EXECUTE ON FUNCTION %I.%I(%s) TO %s;', n.nspname, p.proname, pg_get_function_identity_arguments(p.oid),
               case when a.grantee = 0 then 'PUBLIC' else quote_ident(r.rolname) end), '' order by r.rolname)
               filter (where a.grantee = 0 or r.rolname in ('anon','authenticated','service_role')), '')) as ddl
    from pg_proc p join pg_namespace n on n.oid = p.pronamespace
    cross join lateral aclexplode(coalesce(p.proacl, acldefault('f', p.proowner))) a
    left join pg_roles r on r.oid = a.grantee
    where p.pronamespace in ${SCHEMAS} and p.prokind in ('f','p','w') and a.privilege_type = 'EXECUTE' and ${NOT_EXT("p.oid")}
    group by n.nspname, p.oid, p.proname order by n.nspname, p.proname, pg_get_function_identity_arguments(p.oid)`],
];

const PLATFORM = [
  ["Storage buckets", `
    select format('insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types) values (%L, %L, %s, %s, %s) on conflict (id) do update set public = excluded.public, file_size_limit = excluded.file_size_limit, allowed_mime_types = excluded.allowed_mime_types;',
             id, name, case when public then 'true' else 'false' end, coalesce(file_size_limit::text, 'null'), coalesce(quote_literal(allowed_mime_types::text) || '::text[]', 'null')) as ddl
    from storage.buckets order by id`],
  ["Storage policies", `
    select format(E'DROP POLICY IF EXISTS %I ON storage.objects;\\nCREATE POLICY %I ON %I.%I AS %s FOR %s TO %s%s%s;', policyname, policyname, schemaname, tablename, permissive, cmd,
             (select string_agg(case when r = 'public' then 'PUBLIC' else quote_ident(r) end, ', ') from unnest(roles) r),
             case when qual is not null then E'\\n  USING (' || qual || ')' else '' end,
             case when with_check is not null then E'\\n  WITH CHECK (' || with_check || ')' else '' end) as ddl
    from pg_policies where schemaname = 'storage' order by tablename, policyname`],
  ["Realtime publication tables", `
    select format(E'do $pub$ begin\\n  if not exists (select 1 from pg_publication_tables where pubname = %L and schemaname = %L and tablename = %L) then\\n    alter publication %I add table %I.%I;\\n  end if;\\nend $pub$;',
             pubname, schemaname, tablename, pubname, schemaname, tablename) as ddl
    from pg_publication_tables where pubname = 'supabase_realtime' and schemaname in ('public','private') order by tablename`],
  ["Cron jobs", `
    select format('select cron.schedule(%L, %L, %L);', jobname, schedule, command) as ddl from cron.job order by jobname`],
  ["Migration ledger (one baseline row at the cutoff)", `
    select format(E'create schema if not exists supabase_migrations;\\ncreate table if not exists supabase_migrations.schema_migrations (version text not null primary key, statements text[], name text);\\ninsert into supabase_migrations.schema_migrations (version, name) values (%L, %L) on conflict (version) do nothing;',
             max(version), 'baseline_through_' || max(version)) as ddl
    from supabase_migrations.schema_migrations`],
];

const SECRET_PATTERNS = [/eyJ[A-Za-z0-9_-]{8,}\.[A-Za-z0-9_-]{8,}\.[A-Za-z0-9_-]{8,}/, /sb_secret_[A-Za-z0-9_-]{8,}/, /sbp_[A-Za-z0-9]{20,}/];

async function build(sections, title) {
  const cutoff = (await q(`select max(version) v, count(*) n from supabase_migrations.schema_migrations`))[0];
  const lines = [
    "-- ============================================================",
    `-- STRYT ${title}`,
    `-- source:   production ${PROD}, read from pg_catalog via the Management API`,
    `-- taken:    ${new Date().toISOString()}`,
    `-- cutoff:   migration ledger version ${cutoff.v} (${cutoff.n} rows). Apply migrations with a HIGHER version after this.`,
    "-- method:   scripts/baseline/dump-baseline.mjs — apply with scripts/baseline/apply-baseline.mjs (never to production)",
    "-- ============================================================",
    "",
    "-- @@item header",
    "set check_function_bodies = false;",
  ];
  const counts = {};
  for (const [name, sql] of sections) {
    const rows = await q(sql);
    counts[name] = rows.length;
    for (const [i, r] of rows.entries()) lines.push("", `-- @@item ${name} ${i + 1}/${rows.length}`, r.ddl);
  }
  const body = lines.join("\n") + "\n";
  for (const re of SECRET_PATTERNS) if (re.test(body)) throw new Error(`secret-looking value in ${title}; refusing to write`);
  return { body, counts, cutoff };
}

const outDir = path.join(ROOT, "supabase", "baseline");
fs.mkdirSync(outDir, { recursive: true });
for (const [sections, title, file] of [[SECTIONS, "schema baseline (public + private)", `${date}_schema.sql`], [PLATFORM, "platform state baseline", `${date}_platform_state.sql`]]) {
  const { body, counts, cutoff } = await build(sections, title);
  fs.writeFileSync(path.join(outDir, file), body);
  console.log(`wrote supabase/baseline/${file} (${(Buffer.byteLength(body) / 1024).toFixed(0)} KB), cutoff ${cutoff.v}`);
  for (const [k, v] of Object.entries(counts)) console.log(`  ${String(v).padStart(5)}  ${k}`);
}
console.log("secret scan: clean");
