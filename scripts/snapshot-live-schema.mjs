// Live-schema snapshot, without Docker or a database password.
//
// WHY THIS EXISTS: `supabase db dump` needs Docker, and there is no
// DATABASE_URL on dev machines. This reads the live catalog through the
// Supabase Management API (read-only SELECTs only) and writes a logical
// snapshot: every table, constraint, RLS flag, view, enum, function body,
// trigger, index, policy, grant, realtime table and cron job — i.e. exactly
// what a migration can change. It is the "before" record for any database
// change, and the source for rollback files (function/policy definitions are
// copied verbatim from the catalog, never rewritten by hand).
//
// It is NOT a pg_dump: there is no row data (Supabase backups cover data).
//
// USAGE:
//   node scripts/snapshot-live-schema.mjs supabase/snapshots/<name>.sql
//
// Reads SUPABASE_PERSONAL_ACCESS_TOKEN from .env and never prints it.
// Anything that looks like a secret (JWTs, sb_secret_ keys) is redacted in the
// output file, and its location is reported so the source can be fixed.

import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.join(__dirname, "..");
const OUT = process.argv[2];
if (!OUT) {
  console.error("usage: node scripts/snapshot-live-schema.mjs <output.sql>");
  process.exit(1);
}

function readEnv() {
  const env = {};
  for (const f of [".env", ".env.local"]) {
    const p = path.join(ROOT, f);
    if (!fs.existsSync(p)) continue;
    for (const line of fs.readFileSync(p, "utf8").split(/\r?\n/)) {
      const m = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*)\s*$/);
      if (m && !(m[1] in env)) env[m[1]] = m[2].replace(/^["']|["']$/g, "");
    }
  }
  return env;
}

const env = readEnv();
const TOKEN = env.SUPABASE_PERSONAL_ACCESS_TOKEN;
// SNAPSHOT_PROJECT_REF (e.g. the staging ref) overrides the project from .env. Default unchanged.
const REF = process.env.SNAPSHOT_PROJECT_REF || (env.VITE_SUPABASE_URL || "").match(/https:\/\/([a-z0-9]+)\.supabase\.co/)?.[1];
if (process.env.SNAPSHOT_PROJECT_REF) console.log(`snapshot project (override): ${REF}`);
if (!TOKEN || !REF) {
  console.error("Missing SUPABASE_PERSONAL_ACCESS_TOKEN or VITE_SUPABASE_URL in .env");
  process.exit(1);
}

const API = `https://api.supabase.com/v1/projects/${REF}`;
const headers = { Authorization: `Bearer ${TOKEN}`, "Content-Type": "application/json" };

async function api(method, url, body) {
  const res = await fetch(url, { method, headers, body: body ? JSON.stringify(body) : undefined });
  const text = await res.text();
  if (!res.ok) throw new Error(`${method} ${url.replace(API, "")} -> HTTP ${res.status}: ${text.slice(0, 300)}`);
  return text ? JSON.parse(text) : null;
}
const q = (sql) => api("POST", `${API}/database/query`, { query: sql });

// Non-extension objects only: PostGIS lives in `public` and owns ~1000 functions.
const NOT_EXT = (col) => `not exists (select 1 from pg_depend d where d.objid = ${col} and d.deptype = 'e')`;

const SECTIONS = [
  ["Extensions", `
    select format('-- %s %s (schema %s)', e.extname, e.extversion, n.nspname) as ddl
    from pg_extension e join pg_namespace n on n.oid = e.extnamespace order by e.extname`],
  ["Enum types", `
    select format('CREATE TYPE %I.%I AS ENUM (%s);', n.nspname, t.typname,
             string_agg(quote_literal(e.enumlabel), ', ' order by e.enumsortorder)) as ddl
    from pg_type t join pg_namespace n on n.oid = t.typnamespace join pg_enum e on e.enumtypid = t.oid
    where n.nspname = 'public' and ${NOT_EXT("t.oid")}
    group by n.nspname, t.typname order by t.typname`],
  ["Tables", `
    select format(E'CREATE TABLE %I.%I (\\n%s\\n);', n.nspname, c.relname,
             string_agg(format('  %I %s%s%s', a.attname, format_type(a.atttypid, a.atttypmod),
               case
                 when a.attgenerated = 's' then ' GENERATED ALWAYS AS (' || pg_get_expr(d.adbin, d.adrelid) || ') STORED'
                 when a.attidentity = 'a' then ' GENERATED ALWAYS AS IDENTITY'
                 when a.attidentity = 'd' then ' GENERATED BY DEFAULT AS IDENTITY'
                 when d.adbin is not null then ' DEFAULT ' || pg_get_expr(d.adbin, d.adrelid)
                 else '' end,
               case when a.attnotnull then ' NOT NULL' else '' end), E',\\n' order by a.attnum)) as ddl
    from pg_class c join pg_namespace n on n.oid = c.relnamespace
    join pg_attribute a on a.attrelid = c.oid and a.attnum > 0 and not a.attisdropped
    left join pg_attrdef d on d.adrelid = c.oid and d.adnum = a.attnum
    where n.nspname = 'public' and c.relkind in ('r', 'p') and ${NOT_EXT("c.oid")}
    group by n.nspname, c.relname order by c.relname`],
  ["Constraints", `
    select format('ALTER TABLE ONLY %s ADD CONSTRAINT %I %s;', k.conrelid::regclass, k.conname, pg_get_constraintdef(k.oid)) as ddl
    from pg_constraint k join pg_class c on c.oid = k.conrelid
    where k.connamespace = 'public'::regnamespace and k.contype in ('p','u','f','c','x') and ${NOT_EXT("c.oid")}
    order by k.conrelid::regclass::text, k.contype, k.conname`],
  ["Row level security", `
    select format('ALTER TABLE %I.%I ENABLE ROW LEVEL SECURITY;', n.nspname, c.relname)
           || case when c.relforcerowsecurity then format(E'\\nALTER TABLE %I.%I FORCE ROW LEVEL SECURITY;', n.nspname, c.relname) else '' end as ddl
    from pg_class c join pg_namespace n on n.oid = c.relnamespace
    where n.nspname = 'public' and c.relkind in ('r','p') and c.relrowsecurity order by c.relname`],
  ["Views", `
    select format(E'CREATE %s %I.%I AS\\n%s', case c.relkind when 'm' then 'MATERIALIZED VIEW' else 'OR REPLACE VIEW' end,
             n.nspname, c.relname, pg_get_viewdef(c.oid, true)) as ddl
    from pg_class c join pg_namespace n on n.oid = c.relnamespace
    where n.nspname = 'public' and c.relkind in ('v','m') and ${NOT_EXT("c.oid")} order by c.relname`],
  ["Functions", `
    select pg_get_functiondef(p.oid) || ';' as ddl
    from pg_proc p
    where p.pronamespace = 'public'::regnamespace and p.prokind in ('f','p','w') and ${NOT_EXT("p.oid")}
    order by p.proname, pg_get_function_identity_arguments(p.oid)`],
  ["Function EXECUTE grants (effective)", `
    select format('GRANT EXECUTE ON FUNCTION public.%I(%s) TO %s;', p.proname, pg_get_function_identity_arguments(p.oid),
             string_agg(case when a.grantee = 0 then 'PUBLIC' else quote_ident(r.rolname) end, ', ' order by r.rolname)) as ddl
    from pg_proc p
    cross join lateral aclexplode(coalesce(p.proacl, acldefault('f', p.proowner))) a
    left join pg_roles r on r.oid = a.grantee
    where p.pronamespace = 'public'::regnamespace and p.prokind in ('f','p','w') and a.privilege_type = 'EXECUTE' and ${NOT_EXT("p.oid")}
    group by p.oid, p.proname order by p.proname, pg_get_function_identity_arguments(p.oid)`],
  ["Triggers", `
    select pg_get_triggerdef(t.oid, true) || ';' as ddl
    from pg_trigger t join pg_class c on c.oid = t.tgrelid join pg_proc p on p.oid = t.tgfoid
    where not t.tgisinternal and (c.relnamespace = 'public'::regnamespace or p.pronamespace = 'public'::regnamespace)
    order by c.relnamespace::regnamespace::text, c.relname, t.tgname`],
  ["Indexes (not backing a constraint)", `
    select i.indexdef || ';' as ddl
    from pg_indexes i join pg_class ic on ic.relname = i.indexname and ic.relnamespace = 'public'::regnamespace
    where i.schemaname = 'public' and not exists (select 1 from pg_constraint k where k.conindid = ic.oid) and ${NOT_EXT("ic.oid")}
    order by i.tablename, i.indexname`],
  ["Policies (public + storage)", `
    select format(E'CREATE POLICY %I ON %I.%I AS %s FOR %s TO %s%s%s;', policyname, schemaname, tablename, permissive, cmd,
             (select string_agg(case when r = 'public' then 'PUBLIC' else quote_ident(r) end, ', ') from unnest(roles) r),
             case when qual is not null then E'\\n  USING (' || qual || ')' else '' end,
             case when with_check is not null then E'\\n  WITH CHECK (' || with_check || ')' else '' end) as ddl
    from pg_policies where schemaname in ('public', 'storage') order by schemaname, tablename, policyname`],
  ["Table grants (API roles)", `
    select format('GRANT %s ON public.%I TO %s;', string_agg(privilege_type, ', ' order by privilege_type), table_name, grantee) as ddl
    from information_schema.role_table_grants
    where table_schema = 'public' and grantee in ('anon', 'authenticated', 'service_role', 'PUBLIC')
    group by table_name, grantee order by table_name, grantee`],
  ["Realtime publication", `
    select format('ALTER PUBLICATION %I ADD TABLE %I.%I;', pubname, schemaname, tablename) as ddl
    from pg_publication_tables where pubname = 'supabase_realtime' order by schemaname, tablename`],
  ["Sequences", `
    select format('-- sequence %I.%I', sequence_schema, sequence_name) as ddl
    from information_schema.sequences where sequence_schema = 'public' order by sequence_name`],
  ["Migration ledger (supabase_migrations.schema_migrations)", `
    select format('-- %s  %s', version, coalesce(name, '')) as ddl
    from supabase_migrations.schema_migrations order by version`],
];

// Secrets must never land in a file headed for git. Redact, and report where.
const SECRET_PATTERNS = [
  ["JWT", /eyJ[A-Za-z0-9_-]{8,}\.[A-Za-z0-9_-]{8,}\.[A-Za-z0-9_-]{8,}/g],
  ["sb_secret key", /sb_secret_[A-Za-z0-9_-]{8,}/g],
];

async function main() {
  const started = new Date().toISOString();
  let backups = "unavailable";
  try {
    const b = await api("GET", `${API}/database/backups`);
    const list = (b?.backups ?? []).filter((x) => x.status === "COMPLETED").map((x) => x.inserted_at).sort();
    backups = `pitr_enabled=${b?.pitr_enabled} walg_enabled=${b?.walg_enabled} completed_backups=${list.length} latest=${list.at(-1) ?? "none"}`;
  } catch (e) {
    backups = `unavailable (${e.message.split(":")[0]})`;
  }

  const parts = [];
  const counts = {};
  for (const [title, sql] of SECTIONS) {
    const rows = await q(sql);
    counts[title] = rows.length;
    parts.push(`-- ════════════════════════════════════════════════════════════\n-- ${title} (${rows.length})\n-- ════════════════════════════════════════════════════════════\n\n` +
      rows.map((r) => r.ddl).join("\n\n"));
  }

  // pg_cron is optional; only read it when the extension exists.
  const hasCron = await q(`select to_regclass('cron.job') is not null as ok`);
  if (hasCron[0]?.ok) {
    const jobs = await q(`select format(E'-- cron job %s  schedule=%s  active=%s\\n-- %s', jobname, schedule, active, replace(command, E'\\n', E'\\n-- ')) as ddl from cron.job order by jobname`);
    counts["Cron jobs"] = jobs.length;
    parts.push(`-- ════════════════════════════════════════════════════════════\n-- Cron jobs (${jobs.length})\n-- ════════════════════════════════════════════════════════════\n\n` + jobs.map((r) => r.ddl).join("\n\n"));
  }

  const header = [
    "-- ============================================================",
    "-- STRYT live schema snapshot (logical, read from the catalog)",
    `-- project:  ${REF}`,
    `-- taken:    ${started}`,
    "-- method:   scripts/snapshot-live-schema.mjs (Management API, read-only SELECTs)",
    `-- backups:  ${backups}`,
    "-- NOT a pg_dump: no row data. Definitions are verbatim from pg_catalog.",
    "-- ============================================================",
    "",
  ].join("\n");

  let body = header + parts.join("\n\n\n") + "\n";

  const findings = [];
  for (const [label, re] of SECRET_PATTERNS) {
    body = body.replace(re, (m, offset) => {
      const line = body.slice(0, offset).split("\n").length;
      findings.push({ label, line });
      return `<REDACTED:${label}>`;
    });
  }

  fs.mkdirSync(path.dirname(path.resolve(ROOT, OUT)), { recursive: true });
  fs.writeFileSync(path.resolve(ROOT, OUT), body, "utf8");

  console.log(`snapshot written: ${OUT}  (${(Buffer.byteLength(body) / 1024).toFixed(0)} KB)`);
  console.log(`backups: ${backups}`);
  for (const [k, v] of Object.entries(counts)) console.log(`  ${String(v).padStart(5)}  ${k}`);
  if (findings.length) {
    console.log(`\nREDACTED ${findings.length} secret-looking value(s):`);
    for (const f of findings) console.log(`  ${f.label} near line ${f.line}`);
  } else {
    console.log("\nsecret scan: nothing secret-looking found");
  }
}

main().catch((e) => {
  console.error("snapshot failed:", e.message);
  process.exit(1);
});
